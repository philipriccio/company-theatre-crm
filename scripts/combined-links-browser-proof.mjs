import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {mkdirSync,writeFileSync} from 'node:fs'
const require=createRequire(import.meta.url)
const {chromium}=require('/opt/homebrew/lib/node_modules/agent-browser/node_modules/playwright-core')
const base=process.env.CRM_ANALYTICS_PREVIEW_URL||'http://127.0.0.1:3194',output='reports/combined-links-2026-10-15'
mkdirSync(output,{recursive:true})
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],results=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
const check=(name)=>{results.push({name,passed:true});console.log(`PASS ${name}`)}
try {
  for(const width of [1440,390,320]) {
    await page.setViewportSize({width,height:1000})
    await page.goto(`${base}/campaigns/analytics`)
    await page.waitForLoadState('networkidle')
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    assert.equal(await page.getByRole('heading',{name:'All emails, together.'}).count(),1)
    assert.ok(Number((await page.locator('.analytics-card strong').first().textContent()).replaceAll(',',''))>=114)
    assert.equal(await page.getByRole('heading',{name:'Clicked links',exact:true}).count(),1)
    assert.ok(await page.locator('#links tbody tr').count()>0)
    await page.screenshot({path:`${output}/combined-${width}.png`,fullPage:true})
    await page.locator('#links').screenshot({path:`${output}/links-${width}.png`})
    check(`combined report layout ${width}`)
  }
  await page.setViewportSize({width:1440,height:1000})
  await page.getByLabel('Sent from',{exact:true}).fill('2026-10-14')
  await page.getByLabel('Sent through',{exact:true}).fill('2026-10-14')
  await page.getByLabel('Search recipients',{exact:true}).fill('combined-proof')
  await Promise.all([page.waitForURL(/from=2026-10-14/),page.getByRole('button',{name:'Apply filters'}).click()])
  assert.deepEqual(await page.locator('.analytics-card strong').allTextContents(),['2','1','1','1'])
  assert.equal(await page.locator('#recipients tbody tr').count(),2)
  assert.ok((await page.locator('#recipients .analytics-pagination').innerText()).includes('2 matching emails'))
  const href=await page.getByRole('link',{name:'Export matching emails'}).getAttribute('href')
  const response=await page.request.get(base+href)
  assert.equal(response.status(),200);assert.equal((await response.text()).trim().split('\r\n').length,3)
  const linkHref=await page.getByRole('link',{name:'Export matching links'}).getAttribute('href')
  const linkResponse=await page.request.get(base+linkHref)
  assert.equal(linkResponse.status(),200)
  assert.equal(await page.locator('#links tbody tr').count(),2)
  const linkCsv=await linkResponse.text()
  assert.equal(linkCsv.trim().split('\r\n').length,3)
  assert.match(linkCsv,/placement-2/)
  check('real date/search form and totals/table/link CSV parity')
  await page.getByLabel('Outcome',{exact:true}).selectOption('soft')
  await Promise.all([page.waitForURL(/filter=soft/),page.getByRole('button',{name:'Apply filters'}).click()])
  assert.deepEqual(await page.locator('.analytics-card strong').allTextContents(),['1','0','1','1'])
  assert.equal(await page.locator('#recipients tbody tr').count(),1)
  await page.locator('#recipients tbody td:first-child > a').first().click()
  await page.waitForURL(/recipients\/combined-proof-2/)
  assert.ok((await page.locator('body').innerText()).includes('Transient:General'))
  check('outcome filter and evidence drilldown')
  await page.goto(`${base}/campaigns/analytics?from=2026-10-15&to=2026-10-14`)
  assert.ok((await page.locator('.email-analytics [role=alert]').innerText()).includes('start date'))
  assert.equal(await page.locator('#recipients tbody tr').count(),0)
  assert.equal(await page.getByRole('link',{name:'Export matching emails'}).count(),0)
  check('reversed dates explicit fail-closed report')
  await page.getByRole('link',{name:'All emails · reset'}).click()
  await page.waitForURL('**/campaigns/analytics')
  assert.equal(await page.getByLabel('Sent from',{exact:true}).inputValue(),'')
  assert.ok(Number((await page.locator('.analytics-card strong').first().textContent()).replaceAll(',',''))>=114)
  check('all-time reset restores aggregate')
  await page.getByRole('link',{name:'Refresh totals'}).click()
  await page.waitForLoadState('networkidle')
  assert.equal(await page.getByRole('heading',{name:'All emails, together.'}).count(),1)
  check('refresh reloads live server report')
  await page.goto(`${base}/campaigns/analytics-showcase/analytics`)
  assert.deepEqual(await page.locator('.analytics-card strong').allTextContents(),['90','60','30','6'])
  await page.getByRole('link',{name:'All emails together',exact:true}).click()
  await page.waitForURL('**/campaigns/analytics')
  check('single-batch regression and combined navigation')
  assert.equal(await page.locator('.workspace-nav a[aria-current="page"]').count(),1)
  assert.ok((await page.locator('.workspace-nav a[aria-current="page"]').textContent()).includes('Email analytics'))
  check('dedicated sidebar analytics navigation has one active item')
  assert.deepEqual(errors,[])
  writeFileSync(`${output}/browser.json`,JSON.stringify({results,errors},null,2)+'\n')
  console.log(JSON.stringify({checks:results.length,passed:results.length,errors}))
} finally {await browser.close()}
